from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (
    HRFlowable,
    Image,
    KeepTogether,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

ACCENT = colors.HexColor("#c7ff2f")
DARK = colors.HexColor("#0a0a0a")
SURFACE = colors.HexColor("#111827")
MUTED = colors.HexColor("#6b7280")
BORDER = colors.HexColor("#e5e7eb")
RED = colors.HexColor("#ef4444")
AMBER = colors.HexColor("#f59e0b")
GREEN = colors.HexColor("#10b981")
BG_LIGHT = colors.HexColor("#f9fafb")
WHITE = colors.HexColor("#ffffff")

S_TITLE = ParagraphStyle("title", fontName="Helvetica-Bold", fontSize=18, textColor=DARK, leading=22, spaceAfter=2 * mm)
S_SUB = ParagraphStyle("sub", fontName="Helvetica", fontSize=9, textColor=MUTED, leading=12.5, spaceAfter=3.5 * mm)
S_H2 = ParagraphStyle("h2", fontName="Helvetica-Bold", fontSize=12, textColor=DARK, leading=16, spaceBefore=4 * mm, spaceAfter=2.5 * mm)
S_BODY = ParagraphStyle("body", fontName="Helvetica", fontSize=8.5, textColor=DARK, leading=12)
S_LABEL = ParagraphStyle("label", fontName="Helvetica-Bold", fontSize=7.5, textColor=MUTED, leading=9.5, spaceBefore=1.5 * mm, spaceAfter=0.5 * mm)
S_CALLOUT = ParagraphStyle("callout", fontName="Helvetica", fontSize=8.5, textColor=DARK, leading=12)
S_TABLE_HDR = ParagraphStyle("th", fontName="Helvetica-Bold", fontSize=7.5, textColor=WHITE, leading=9.5)
S_TABLE_CELL = ParagraphStyle("td", fontName="Helvetica", fontSize=8, textColor=DARK, leading=10.5)
S_TABLE_MUTED = ParagraphStyle("td_muted", fontName="Helvetica", fontSize=7.5, textColor=MUTED, leading=10)
S_FOOT = ParagraphStyle("foot", fontName="Helvetica", fontSize=7.5, textColor=MUTED, alignment=1)

CANONICAL_SIGNALS = [
    {"id": "headline", "canon": "message match", "label": "Message Match", "desc": "Does the page promise match the expectation created by referring ad or search?"},
    {"id": "cta", "canon": "CTA clarity", "label": "CTA Clarity", "desc": "Is the next step obvious and proportionate to visitor intent?"},
    {"id": "above_fold", "canon": "above-fold clarity", "label": "Above-Fold Clarity", "desc": "Can a visitor understand the offer and next action in the first viewport?"},
    {"id": "social_proof", "canon": "trust signals", "label": "Trust Signals", "desc": "Does the page support its claims with proximate proof before asking for commitment?"},
    {"id": "load_speed", "canon": "load speed", "label": "Load Speed", "desc": "Does the page become interactive quickly enough to prevent paid bounces?"},
    {"id": "mobile", "canon": "mobile viewport", "label": "Mobile Viewport", "desc": "Is the primary action visible and usable on small viewports?"},
    {"id": "ad_signals", "canon": "ad tracking", "label": "Ad Tracking", "desc": "Can paid clicks be connected to conversions and ROAS without guessing?"},
    {"id": "seo_foundations", "canon": "SEO foundations", "label": "SEO Foundations", "desc": "Can search systems retrieve and interpret core page architecture?"},
    {"id": "ai_readiness", "canon": "AI readiness", "label": "AI Readiness", "desc": "Can answer engines identify, verify, and cite page answers accurately?"},
]


def _clean_str(value: Any) -> str:
    """Sanitize string removing em-dashes per repository doctrine."""
    if not value:
        return ""
    text = str(value).replace("\u2014", " - ").replace("\u2013", " - ")
    return text.strip()


def _fmt_date(iso: object) -> str:
    if not iso:
        return datetime.now(timezone.utc).strftime("%B %d, %Y")
    if isinstance(iso, datetime):
        dt = iso
    else:
        try:
            dt = datetime.fromisoformat(str(iso).replace("Z", "+00:00"))
        except ValueError:
            return str(iso)
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt.strftime("%B %d, %Y")


def _fetch_logo(url: str) -> Optional[Image]:
    """Best-effort remote logo fetch. Returns None on any failure."""
    try:
        if not url.startswith(("http://", "https://")):
            return None
        req = urllib.request.Request(url, headers={"User-Agent": "NebulaReport/1.0"})
        with urllib.request.urlopen(req, timeout=3) as resp:
            ctype = resp.headers.get("Content-Type", "")
            if "image" not in ctype:
                return None
            data = resp.read(2 * 1024 * 1024)
        img = Image(io.BytesIO(data))
        max_w, max_h = 40 * mm, 14 * mm
        ratio = min(max_w / img.imageWidth, max_h / img.imageHeight, 1.0)
        img.drawWidth = img.imageWidth * ratio
        img.drawHeight = img.imageHeight * ratio
        return img
    except Exception:
        return None


def generate_audit_pdf(
    audit_data: dict,
    findings: list,
    agency_name: Optional[str] = None,
    agency_logo_url: Optional[str] = None,
) -> bytes:
    """Render an audit report PDF matching the complete report structure and return it as bytes."""
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        leftMargin=14 * mm,
        rightMargin=14 * mm,
        topMargin=14 * mm,
        bottomMargin=14 * mm,
        title=f"Conversion Audit Report - {audit_data.get('url', '')}",
        author=agency_name or "Nebula Components",
    )
    content_width = doc.width

    engine_out = audit_data.get("engine_output") if isinstance(audit_data.get("engine_output"), dict) else {}
    dimensions = engine_out.get("dimensions") or audit_data.get("dimensions") or {}
    raw_score = audit_data.get("score")
    score_val = float(raw_score) if raw_score is not None else 7.0
    if score_val > 10.0:
        score_val = score_val / 10.0

    comp_val = engine_out.get("composite")
    comp_score = float(comp_val) if comp_val is not None else score_val
    if comp_score > 10.0:
        comp_score = comp_score / 10.0

    grade = _clean_str(audit_data.get("grade") or "B")
    url = _clean_str(audit_data.get("url") or "")
    audit_id = _clean_str(str(audit_data.get("audit_id") or audit_data.get("id") or ""))[:8]
    date_str = _fmt_date(audit_data.get("completed_at") or audit_data.get("created_at"))

    # Parse and prioritize findings
    raw_findings = findings or audit_data.get("findings") or []
    findings_list: List[Dict[str, Any]] = []
    for f in raw_findings:
        if isinstance(f, dict):
            findings_list.append({
                "key": _clean_str(f.get("key") or ""),
                "label": _clean_str(f.get("label") or f.get("key") or "Conversion Condition"),
                "issue": _clean_str(f.get("issue") or "Condition unfulfilled"),
                "fix": _clean_str(f.get("fix") or "Optimize landing page conversion condition"),
                "impact": float(f.get("impact") or 5.0),
                "effort": int(f.get("effort") or 3),
                "quadrant": _clean_str(f.get("quadrant") or "quick_win").replace("_", " ").title(),
                "selector": _clean_str(f.get("selector") or ""),
            })

    # Sort findings by impact descending
    findings_list.sort(key=lambda x: -x["impact"])

    cro = engine_out.get("citable", {}).get("cro") or audit_data.get("citable", {}).get("cro") or {}
    posture = _clean_str(cro.get("conversion_status") or ("READY" if comp_score >= 7.0 else "NEEDS ATTENTION")).upper()
    failing_count = len(findings_list)

    story: list = []

    # 1. Header
    logo = _fetch_logo(agency_logo_url) if agency_logo_url else None
    brand = _clean_str(agency_name) if agency_name else "NEBULA COMPONENTS"

    if logo is not None:
        hdr_table = Table(
            [[
                logo,
                Table([
                    [Paragraph(f"<b>{brand}</b>", ParagraphStyle("hb", fontName="Helvetica-Bold", fontSize=13, textColor=DARK))],
                    [Paragraph(f"<font color='#6b7280' size=8>AUDIT ID: <b>{audit_id}</b> · {date_str}</font>", ParagraphStyle("hr", fontName="Helvetica", fontSize=8))],
                ], colWidths=[content_width - 45 * mm]),
            ]],
            colWidths=[45 * mm, content_width - 45 * mm],
        )
    else:
        hdr_table = Table(
            [[
                Paragraph(f"<b>{brand}</b>", ParagraphStyle("hb", fontName="Helvetica-Bold", fontSize=13, textColor=DARK)),
                Paragraph(f"<font color='#6b7280' size=8>AUDIT ID: <b>{audit_id}</b> · {date_str}</font>", ParagraphStyle("hr", fontName="Helvetica", fontSize=8, alignment=2)),
            ]],
            colWidths=[content_width * 0.6, content_width * 0.4],
        )

    hdr_table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 1.5 * mm),
    ]))
    story.append(hdr_table)
    story.append(HRFlowable(width="100%", thickness=1, color=BORDER, spaceBefore=1 * mm, spaceAfter=3.5 * mm))

    # Title & Subtitle
    story.append(Paragraph("Landing Page Conversion Audit Report", S_TITLE))
    story.append(Paragraph("Evidence-backed analysis of observable conversion mechanics and 9 core conversion signals.", S_SUB))

    # 2. Executive Scorecard
    score_color = GREEN if comp_score >= 7.0 else (AMBER if comp_score >= 5.0 else RED)
    score_box = [
        Paragraph(f"<font size=26 color='{score_color.hexval().replace('0x', '#')}'><b>{comp_score:.1f}</b></font><font size=13 color='#9ca3af'>/10</font>", ParagraphStyle("sc", fontName="Helvetica-Bold", leading=28, alignment=1)),
        Spacer(1, 1.5 * mm),
        Paragraph(f"<font color='#ffffff' size=9><b>GRADE {grade}</b></font>", ParagraphStyle("gb", fontName="Helvetica-Bold", leading=11, alignment=1)),
    ]

    meta_rows = [
        [Paragraph("<b>Target URL:</b>", S_TABLE_MUTED), Paragraph(f"<font color='#111827'>{url}</font>", S_TABLE_CELL)],
        [Paragraph("<b>Conversion Posture:</b>", S_TABLE_MUTED), Paragraph(f"<b>{posture}</b>", S_TABLE_CELL)],
        [Paragraph("<b>Failed Conditions:</b>", S_TABLE_MUTED), Paragraph(f"<font color='{RED.hexval().replace('0x', '#')}'><b>{failing_count} of 9 signals</b></font>", S_TABLE_CELL)],
        [Paragraph("<b>Evaluation Scope:</b>", S_TABLE_MUTED), Paragraph("9 Canonical Signals · Deterministic Inspection", S_TABLE_CELL)],
    ]
    meta_table = Table(meta_rows, colWidths=[36 * mm, content_width - 44 * mm - 36 * mm - 6 * mm])
    meta_table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 0.8 * mm),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 0.8 * mm),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
    ]))

    scorecard_table = Table(
        [[
            Table([[b] for b in score_box], colWidths=[40 * mm], style=[
                ("BACKGROUND", (0, 0), (-1, -1), SURFACE),
                ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 2.5 * mm),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5 * mm),
                ("BOX", (0, 0), (-1, -1), 1, SURFACE),
            ]),
            meta_table,
        ]],
        colWidths=[44 * mm, content_width - 44 * mm],
    )
    scorecard_table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("BACKGROUND", (0, 0), (-1, -1), BG_LIGHT),
        ("BOX", (0, 0), (-1, -1), 0.75, BORDER),
        ("LEFTPADDING", (0, 0), (-1, -1), 3 * mm),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4 * mm),
        ("TOPPADDING", (0, 0), (-1, -1), 2.5 * mm),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5 * mm),
    ]))
    story.append(scorecard_table)
    story.append(Spacer(1, 3 * mm))

    # 3. Strategic Diagnosis ("Your Biggest Leak")
    strat = _clean_str(engine_out.get("strategic_finding") or "")
    if not strat and findings_list:
        worst_f = findings_list[0]
        strat = f"Highest-impact leak identified in {worst_f.get('label')}: {worst_f.get('issue')}."
    if strat:
        diag_box = Table(
            [[
                Paragraph(
                    f"<b>STRATEGIC DIAGNOSIS:</b> {strat}",
                    S_CALLOUT,
                )
            ]],
            colWidths=[content_width],
        )
        diag_box.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), BG_LIGHT),
            ("BOX", (0, 0), (-1, -1), 0.75, BORDER),
            ("LINEBEFORE", (0, 0), (0, -1), 3, DARK),
            ("LEFTPADDING", (0, 0), (-1, -1), 3.5 * mm),
            ("RIGHTPADDING", (0, 0), (-1, -1), 3.5 * mm),
            ("TOPPADDING", (0, 0), (-1, -1), 2.2 * mm),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 2.2 * mm),
        ]))
        story.append(diag_box)
        story.append(Spacer(1, 3 * mm))

    # 4. Nine Core Conversion Signals Table
    story.append(Paragraph("Nine Core Conversion Signals", S_H2))
    sig_rows = [
        [
            Paragraph("SIGNAL", S_TABLE_HDR),
            Paragraph("STATUS", S_TABLE_HDR),
            Paragraph("SCORE", S_TABLE_HDR),
            Paragraph("EVALUATION CRITERIA", S_TABLE_HDR),
        ]
    ]

    for sig in CANONICAL_SIGNALS:
        s_id = sig["id"]
        s_dim = dimensions.get(s_id) or {}
        s_score = float(s_dim.get("score", 10.0))
        if s_score > 10.0:
            s_score = s_score / 10.0

        is_fail = any(
            (f.get("key") == s_id)
            or (s_id in f.get("key", "").lower())
            or (f.get("label", "").lower() == sig["label"].lower())
            for f in findings_list
        ) or (s_score < 7.0)

        badge_txt = "FAIL" if is_fail else "PASS"
        b_color = RED if is_fail else GREEN

        status_p = Paragraph(f"<font color='{b_color.hexval().replace('0x', '#')}'><b>{badge_txt}</b></font>", S_TABLE_CELL)
        score_p = Paragraph(f"<b>{s_score:.1f}</b>/10", S_TABLE_CELL)
        desc_p = Paragraph(sig["desc"], S_TABLE_MUTED)

        sig_rows.append([
            Paragraph(f"<b>{sig['label']}</b>", S_TABLE_CELL),
            status_p,
            score_p,
            desc_p,
        ])

    sig_table = Table(
        sig_rows,
        colWidths=[42 * mm, 20 * mm, 22 * mm, content_width - 84 * mm],
    )
    sig_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), SURFACE),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [WHITE, BG_LIGHT]),
        ("TOPPADDING", (0, 0), (-1, -1), 1.5 * mm),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 1.5 * mm),
        ("LEFTPADDING", (0, 0), (-1, -1), 2.5 * mm),
        ("RIGHTPADDING", (0, 0), (-1, -1), 2.5 * mm),
    ]))
    story.append(sig_table)

    # 5. Prioritized Conversion Findings
    story.append(Spacer(1, 3.5 * mm))
    story.append(Paragraph("Prioritized Conversion Findings", S_H2))

    if not findings_list:
        story.append(Paragraph("No failing conditions detected. All conversion signals met threshold.", S_BODY))
    else:
        for idx, f in enumerate(findings_list, 1):
            impact = float(f.get("impact") or 5.0)
            effort = int(f.get("effort") or 3)
            quadrant = f.get("quadrant") or "Quick Win"
            label = f.get("label") or f"Finding {idx}"
            issue = f.get("issue") or "Condition unfulfilled"
            fix = f.get("fix") or "Optimize landing page conversion condition"

            b_color = RED if impact >= 7.0 else (AMBER if impact >= 4.0 else MUTED)
            severity = "CRITICAL" if impact >= 7.0 else ("WARNING" if impact >= 4.0 else "ADVISORY")

            card_content = [
                Paragraph(
                    f"<b>{idx}. {label}</b>&nbsp;&nbsp;&nbsp;&nbsp;"
                    f"<font color='{b_color.hexval().replace('0x', '#')}'><b>{severity} · Impact {impact:g}/10</b></font>&nbsp;&nbsp;·&nbsp;&nbsp;"
                    f"<font color='#6b7280'>Effort: {effort}/5 ({quadrant})</font>",
                    ParagraphStyle("fh", fontName="Helvetica-Bold", fontSize=9, textColor=DARK, leading=12),
                ),
                Spacer(1, 1 * mm),
                Paragraph("<b>OBSERVABLE ISSUE:</b>", S_LABEL),
                Paragraph(issue, S_BODY),
                Spacer(1, 0.8 * mm),
                Paragraph("<b>RECOMMENDED REPAIR:</b>", S_LABEL),
                Paragraph(fix, S_BODY),
            ]

            f_table = Table([[card_content]], colWidths=[content_width])
            f_table.setStyle(TableStyle([
                ("BOX", (0, 0), (-1, -1), 0.75, BORDER),
                ("LINEBEFORE", (0, 0), (0, -1), 2.5, b_color),
                ("BACKGROUND", (0, 0), (-1, -1), BG_LIGHT),
                ("LEFTPADDING", (0, 0), (-1, -1), 3 * mm),
                ("RIGHTPADDING", (0, 0), (-1, -1), 3 * mm),
                ("TOPPADDING", (0, 0), (-1, -1), 2.2 * mm),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 2.2 * mm),
            ]))
            story.append(KeepTogether([f_table, Spacer(1, 2 * mm)]))

    # 6. Citable Telemetry & Page Inspection
    story.append(Spacer(1, 3 * mm))
    story.append(Paragraph("Citable CRO Telemetry & Inspection Evidence", S_H2))

    ctas = cro.get("ctas") or []
    forms = cro.get("forms") or []
    analytics = "Installed" if cro.get("analytics_installed", True) else "Not detected"
    h1_align = cro.get("title_to_h1_alignment") or {}
    h1_text = _clean_str(h1_align.get("h1Text") or audit_data.get("page_h1") or "N/A")

    telem_rows = [
        [
            Paragraph("<b>Interactive CTAs</b>", S_TABLE_CELL),
            Paragraph(f"{len(ctas)} detected ({cro.get('hero_cta_count', 0)} in hero)", S_TABLE_CELL),
            Paragraph("<b>Lead Forms</b>", S_TABLE_CELL),
            Paragraph(f"{len(forms)} form(s) analyzed", S_TABLE_CELL),
        ],
        [
            Paragraph("<b>Ad / Analytics Tracking</b>", S_TABLE_CELL),
            Paragraph(f"{analytics}", S_TABLE_CELL),
            Paragraph("<b>Heading H1</b>", S_TABLE_CELL),
            Paragraph(f"{h1_text[:60]}{'...' if len(h1_text) > 60 else ''}", S_TABLE_CELL),
        ],
    ]
    telem_table = Table(telem_rows, colWidths=[38 * mm, 45 * mm, 32 * mm, content_width - 115 * mm])
    telem_table.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
        ("BACKGROUND", (0, 0), (-1, -1), BG_LIGHT),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 1.5 * mm),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 1.5 * mm),
        ("LEFTPADDING", (0, 0), (-1, -1), 2.5 * mm),
        ("RIGHTPADDING", (0, 0), (-1, -1), 2.5 * mm),
    ]))
    story.append(telem_table)

    # 7. Governance & Methodology Notice
    story.append(Spacer(1, 4 * mm))
    story.append(Paragraph(
        "<b>Governance Notice:</b> Nebula Components and Citable provide evidence-bounded analysis of public conversion mechanics. "
        "Findings reflect deterministic page inspection and published industry CRO heuristics. An effect on conversion outcomes is not established. "
        "No warranty or guarantee of conversion rate lift is expressed or implied.",
        ParagraphStyle("gov", fontName="Helvetica", fontSize=7, textColor=MUTED, leading=9.5),
    ))
    story.append(Spacer(1, 2.5 * mm))
    prepared = f"Prepared by {agency_name} · " if agency_name else ""
    story.append(Paragraph(
        f"{prepared}Generated by Nebula Components · nebulacomponents.com · Confidential",
        S_FOOT,
    ))

    doc.build(story)
    return buf.getvalue()
