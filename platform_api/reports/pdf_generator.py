"""Generate a branded audit report PDF with reportlab.

Layout:
  Header   - agency name/logo when set, else Nebula default
  Scorecard - condition score, grade, URL, posture, failed signals count
  Diagnosis - strategic diagnosis and biggest conversion leak
  Signals  - 9 core conversion signals table (status, score, criteria)
  Findings - prioritized conversion findings (severity, impact, effort, issue, fix)
  Telemetry - Citable CRO telemetry (interactive CTAs, forms, ad tracking, H1)
  Notice   - governance and methodology disclosure
  Footer   - generated by Nebula Components
"""

