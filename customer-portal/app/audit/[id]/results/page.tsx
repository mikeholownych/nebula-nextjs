import { cookies, headers } from 'next/headers'
import { notFound } from 'next/navigation'
import ResultsClient from './ResultsClient'
import { verifyAuditUnlock, readAuditUnlock } from '@/app/lib/audit-unlock-token'
import { parseAuditResult, type AuditResult } from './auditResultSchema'

interface Props {
  params: Promise<{ id: string }>
  searchParams: Promise<{ share?: string; unlock?: string }>
}

const API_BASE = process.env.PLATFORM_API_URL ?? 'http://127.0.0.1:8001'
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

async function fetchAuditPayload(
  id: string,
  options: { share?: string; cookie?: string | null } = {},
): Promise<unknown | null> {
  const qs = options.share ? `?share=${encodeURIComponent(options.share)}` : ''
  const res = await fetch(`${API_BASE}/audit/${id}${qs}`, {
    cache: 'no-store',
    signal: AbortSignal.timeout(3_000),
    headers: {
      ...(options.cookie ? { cookie: options.cookie } : {}),
    },
  })
  if (!res.ok) return null
  return res.json()
}

function parsedAudit(payload: unknown): AuditResult | null {
  try {
    return parseAuditResult(payload)
  } catch {
    return null
  }
}

export default async function ResultsPage({ params, searchParams }: Props) {
  const { id } = await params
  const { share, unlock } = await searchParams

  if (!UUID_RE.test(id)) notFound()

  const cookieStore = await cookies()
  const headersList = await headers()
  const cookie = headersList.get('cookie')
  const authorization = headersList.get('authorization')
  let auditPayload: unknown | null = null

  // --- Path 1: Cookie unlock (visitor submitted their email on this device) ---
  const cookieUnlocked = verifyAuditUnlock(id, cookieStore.get(`audit_unlock_${id}`)?.value)

  // --- Path 2: Workspace session (logged-in user bypasses the email gate) ---
  let sessionUnlocked = false
  if (!cookieUnlocked && (cookie || authorization)) {
    try {
      const res = await fetch(`${API_BASE}/api/auth/me`, {
        headers: {
          ...(cookie ? { cookie } : {}),
          ...(authorization ? { authorization } : {}),
        },
        cache: 'no-store',
        signal: AbortSignal.timeout(3_000),
      })
      if (res.ok) {
        const user = await res.json()
        const userEmail = typeof user.email === 'string' ? user.email.trim().toLowerCase() : ''
        if (userEmail) {
          const payload = await fetchAuditPayload(id, { cookie })
          if (payload && typeof payload === 'object') {
            const owner = typeof (payload as { email?: string }).email === 'string'
              ? (payload as { email: string }).email.trim().toLowerCase()
              : ''
            sessionUnlocked = Boolean(owner && owner === userEmail)
            if (sessionUnlocked) auditPayload = payload
          }
        }
      }
    } catch {
      // auth service down - fall through to other unlock paths
    }
  }

  // --- Path 3: Share-token unlock (third-party link) ---
  let sharedView = false
  let tokenUnlocked = false

  if (!cookieUnlocked && !sessionUnlocked && share && /^[\w-]{10,64}$/.test(share)) {
    try {
      const payload = await fetchAuditPayload(id, { share, cookie })
      if (payload) {
        tokenUnlocked = true
        sharedView = true
        auditPayload = payload
      }
    } catch {
      // upstream down - treat as locked; visitor will see the teaser
    }
  }

  // --- Path 4: Outreach unlock token (?unlock=<signed-token>) ---
  // Generated by deliver_audit.py after scoring, embedded in the outreach email's
  // direct Stripe link and results page URL. Uses the same HMAC-signed token as the
  // cookie unlock path, so the email is verified without a separate DB lookup.
  // This eliminates the email gate for recipients who already received an audit via
  // outreach - they should land directly on an unlocked results page.
  let outreachUnlocked = false
  if (!cookieUnlocked && !sessionUnlocked && !tokenUnlocked && unlock) {
    const verified = readAuditUnlock(id, unlock)
    if (verified) {
      outreachUnlocked = true
      // Promote to cookie so the unlock persists across navigation
      // (the cookie write happens client-side via a header - we return it here
      //  as a Set-Cookie header so it lands before the first paint)
    }
  }

  const unlocked = cookieUnlocked || sessionUnlocked || tokenUnlocked || outreachUnlocked

  if (!auditPayload) {
    try {
      auditPayload = await fetchAuditPayload(id, { share, cookie })
    } catch {
      auditPayload = null
    }
  }

  if (!auditPayload) notFound()

  const initialResults = parsedAudit(auditPayload)

  return (
    <ResultsClient
      auditId={id}
      unlocked={unlocked}
      sharedView={sharedView}
      shareToken={share}
      unlockToken={unlock}
      initialResults={initialResults}
    />
  )
}
