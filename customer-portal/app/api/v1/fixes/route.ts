import { NextRequest, NextResponse } from 'next/server'

const API_BASE = process.env.PLATFORM_API_URL ?? 'http://127.0.0.1:8001'

interface AuditFinding {
  key: string
  label: string
  impact: number
  effort: number
  quadrant: string
  issue?: string
  fix?: string
  evidence?: {
    selector?: string
    measured?: string
    required?: string
    delta?: string
    confidence?: string
  }
}

interface AuditData {
  audit_id: string
  url: string
  score: number
  grade: string
  composite?: number
  findings: AuditFinding[]
  created_at?: string
}

async function validateKey(rawKey: string): Promise<{ valid: boolean; email?: string; plan?: string }> {
  if (!rawKey || !rawKey.startsWith('nbk_')) return { valid: false }
  try {
    const res = await fetch(`${API_BASE}/workspace/api-keys/validate`, {
      headers: { Authorization: `Bearer ${rawKey}` },
      signal: AbortSignal.timeout(3000),
    })
    if (!res.ok) return { valid: false }
    const data = await res.json()
    return { valid: data.valid === true, email: data.email, plan: data.plan }
  } catch {
    return { valid: false }
  }
}

export function formatAgentPayload(data: AuditData, isMarkdown = false) {
  const leaks = (data.findings || []).map((f, i) => {
    const selector = f.evidence?.selector && f.evidence.selector !== 'N/A'
      ? f.evidence.selector
      : 'Hero section / Main CTA'
    const measured = f.evidence?.measured || 'Fails conversion benchmark'
    const required = f.evidence?.required || 'Meets conversion standard'

    let suggestedSnippet = ''
    if (f.key.includes('contrast') || f.key.includes('cta')) {
      suggestedSnippet = `/* Ensure primary CTA has minimum 4.5:1 contrast and strong visual hierarchy */\n${selector} {\n  background-color: #c7ff2f;\n  color: #09090b;\n  font-weight: 700;\n  padding: 0.75rem 1.5rem;\n  border-radius: 0.5rem;\n}`
    } else if (f.key.includes('schema') || f.key.includes('faq')) {
      suggestedSnippet = `<script type="application/ld+json">\n{\n  "@context": "https://schema.org",\n  "@type": "FAQPage",\n  "mainEntity": [\n    {\n      "@type": "Question",\n      "name": "How does your service work?",\n      "acceptedAnswer": {\n        "@type": "Answer",\n        "text": "Detailed conversion explanation here."\n      }\n    }\n  ]\n}\n</script>`
    } else if (f.key.includes('mobile') || f.key.includes('viewport')) {
      suggestedSnippet = `/* Fix mobile padding and prevent horizontal scroll */\n@media (max-width: 640px) {\n  ${selector} {\n    padding-left: 1rem;\n    padding-right: 1rem;\n    width: 100%;\n    max-width: 100vw;\n    box-sizing: border-box;\n  }\n}`
    } else {
      suggestedSnippet = `// Apply fix for ${f.label}:\n// ${f.fix || 'Improve component clarity and visible value proposition'}`
    }

    return {
      index: i + 1,
      id: `leak_${f.key}`,
      key: f.key,
      label: f.label,
      severity: f.impact >= 8 ? 'CRITICAL' : f.impact >= 5 ? 'WARNING' : 'ADVISORY',
      impact_score: f.impact,
      effort_score: f.effort,
      target_dom_selector: selector,
      measured_evidence: measured,
      required_standard: required,
      issue_description: f.issue || 'Conversion leak detected on public landing page.',
      remediation_fix: f.fix || 'Refactor component according to conversion best practices.',
      suggested_snippet: suggestedSnippet,
    }
  })

  if (isMarkdown) {
    const mdList = leaks
      .map(
        (l) => `### ${l.index}. [${l.severity}] ${l.label}
- **Target DOM Selector:** \`${l.target_dom_selector}\`
- **Impact / Effort:** Priority ${l.impact_score}/10 | Effort ${l.effort_score}/10
- **Evidence:** Measured: ${l.measured_evidence} (Required: ${l.required_standard})
- **Issue:** ${l.issue_description}
- **Actionable Fix:** ${l.remediation_fix}
\`\`\`
${l.suggested_snippet}
\`\`\``
      )
      .join('\n\n')

    return `# Nebula Conversion Remediation Directives
**Target URL:** ${data.url}
**Audit Score:** ${data.score}/100 (Grade: ${data.grade})
**Total Detected Leaks:** ${leaks.length}

## Instructions for Autonomous AI Coding Agent:
1. Search your project workspace for components rendering the DOM selectors indicated below.
2. Apply the exact CSS, copy, or markup modifications specified in the actionable fix.
3. Ensure mobile responsiveness (375px viewport) and keep primary CTAs above the fold.
4. Run your test suite to ensure clean build compilation.

## Prioritized Conversion Leaks:
${mdList}

---
*Generated by Nebula Conversion Intelligence API*
`
  }

  return {
    protocol: 'nebula-agent-fix/v1',
    status: 'success',
    audit_id: data.audit_id,
    url: data.url,
    overall_score: data.score,
    grade: data.grade,
    composite_score: data.composite ?? data.score,
    summary: `Found ${leaks.length} conversion and citability leaks on ${data.url}. Recommended priorities: ${leaks.filter(l => l.severity === 'CRITICAL').length} critical issues.`,
    agent_directives: [
      '1. Search the codebase for components matching the target DOM selectors.',
      '2. Implement the remediation fixes and suggested snippets.',
      '3. Verify that above-the-fold CTA contrast and mobile layout requirements are met.',
      '4. Re-run your tests to ensure no layout regressions.',
    ],
    leaks,
    verification: {
      recheck_url: `https://nebulacomponents.com/api/v1/fixes?url=${encodeURIComponent(data.url)}`,
      success_threshold: 'composite_score >= 85 and 0 critical leaks',
    },
  }
}

export async function GET(request: NextRequest) {
  const authHeader = request.headers.get('authorization') || ''
  const apiKeyHeader = request.headers.get('x-api-key') || ''
  const apiKeyQuery = request.nextUrl.searchParams.get('api_key') || ''
  const rawKey = authHeader.replace(/^Bearer\s+/i, '').trim() || apiKeyHeader || apiKeyQuery

  const targetUrl = request.nextUrl.searchParams.get('url')?.trim()
  const format = request.nextUrl.searchParams.get('format') || ''
  const acceptHeader = request.headers.get('accept') || ''
  const isMarkdown = format === 'md' || format === 'markdown' || acceptHeader.includes('text/markdown')

  // Check auth
  if (rawKey) {
    const keyAuth = await validateKey(rawKey)
    if (!keyAuth.valid) {
      return NextResponse.json(
        {
          error: 'Invalid or expired Nebula API key.',
          hint: 'Generate an API key in your customer workspace at https://nebulacomponents.com/workspace?tab=settings',
        },
        { status: 401 }
      )
    }
  }

  if (!targetUrl) {
    return NextResponse.json(
      {
        protocol: 'nebula-agent-fix/v1',
        description: 'Nebula Direct AI Agent Fix API. Supply a target URL or audit ID to receive machine-readable conversion fix directives.',
        usage: {
          by_url: 'GET /api/v1/fixes?url=https://example.com',
          by_audit_id: 'GET /api/v1/fixes/audit_abc123',
          headers: {
            Authorization: 'Bearer nbk_your_api_key',
            Accept: 'application/json (or text/markdown)',
          },
        },
      },
      { status: 200 }
    )
  }

  try {
    // Run audit scan or fetch recent for this URL
    const runRes = await fetch(`${API_BASE}/audit/run`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ url: targetUrl }),
      signal: AbortSignal.timeout(20000),
    })

    if (!runRes.ok) {
      return NextResponse.json(
        { error: 'Failed to retrieve conversion audit for URL', status: runRes.status },
        { status: 502 }
      )
    }

    const auditData: AuditData = await runRes.json()
    const payload = formatAgentPayload(auditData, isMarkdown)

    if (isMarkdown && typeof payload === 'string') {
      return new NextResponse(payload, {
        status: 200,
        headers: { 'Content-Type': 'text/markdown; charset=utf-8' },
      })
    }

    return NextResponse.json(payload, { status: 200 })
  } catch (err: unknown) {
    return NextResponse.json(
      {
        error: 'Failed to generate agent fix instructions',
        details: err instanceof Error ? err.message : 'Unknown error',
      },
      { status: 500 }
    )
  }
}
